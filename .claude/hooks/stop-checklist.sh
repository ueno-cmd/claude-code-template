#!/bin/bash
# stop-checklist.sh
# タスク完了前に最低限の確認を行うフック

echo ""
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "📋 [HOOK] タスク完了前チェックリスト"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"

FAILED=0

# -----------------------------------------------
# ① ステアリングファイルの存在確認
# -----------------------------------------------
if [ ! -f "docs/steering/requirements.md" ]; then
  echo "⚠️  docs/steering/requirements.md が見つかりません。"
  echo "   /starter コマンドでステアリングファイルを生成しましたか？"
  FAILED=1
fi

# -----------------------------------------------
# ② 未コミットの変更確認
# -----------------------------------------------
if git status --porcelain 2>/dev/null | grep -q "^[^?]"; then
  echo "⚠️  未コミットの変更があります。"
  echo "   意図的な場合は無視してください。"
fi

# -----------------------------------------------
# ③ TODO コメントの残存確認
# -----------------------------------------------
TODO_COUNT=$(grep -rn "TODO\|FIXME\|HACK" \
  --include="*.ts" --include="*.tsx" --include="*.js" \
  --include="*.py" --include="*.md" . 2>/dev/null | \
  grep -v ".git" | wc -l | tr -d ' ')

if [ "$TODO_COUNT" -gt 0 ]; then
  echo "⚠️  TODO / FIXME コメントが ${TODO_COUNT} 件残っています。"
  echo "   意図的な場合は無視してください。"
fi

# -----------------------------------------------
# 結果判定
# -----------------------------------------------
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"

if [ "$FAILED" -eq 1 ]; then
  echo "🚫 必須チェックに未達成項目があります。確認してください。"
  exit 2
fi

echo "✅ チェック完了。タスクを終了します。"
exit 0